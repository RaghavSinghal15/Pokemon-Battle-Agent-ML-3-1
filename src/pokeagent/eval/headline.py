"""Headline evaluation (A7, #83): add up recorded chunks and check the success criteria."""

import json

from pokeagent.config import REPORTS_DIR, SEED
from pokeagent.eval.stats import win_rate_ci

HEADLINE_DIR = REPORTS_DIR / "results" / "headline"
HEADLINE_REPORT = REPORTS_DIR / "results" / "headline.md"
STRATEGIES = {"best_response": "full", "lp": "lp"}  # strategy -> ablation variant of the agent
OPPONENTS = ("random", "max_power", "heuristics")
PAIRINGS = [f"{s}:{o}" for s in STRATEGIES for o in OPPONENTS]


def summarise(results_dir=HEADLINE_DIR) -> list[dict]:
    totals = {}
    for path in sorted(results_dir.glob("*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        key = (r["strategy"], r["opponent"])
        total = totals.setdefault(key, {"games": 0, "wins": 0, "commits": set(), "dates": set()})
        total["games"] += r["games"]
        total["wins"] += r["wins"]
        total["commits"].add(r["source"]["commit"][:7])
        total["dates"].add(r["started_utc"][:10])
    rows = []
    for pairing in PAIRINGS:
        key = tuple(pairing.split(":"))
        if key not in totals:
            continue
        t = totals[key]
        rate, low, high = win_rate_ci(t["wins"], t["games"])
        rows.append(
            {"strategy": key[0], "opponent": key[1], **t, "rate": rate, "low": low, "high": high}
        )
    return rows


def markdown(rows: list[dict]) -> str:
    lines = [
        "# Headline evaluation",
        "",
        "The full agent (value-utility payoff table, LightGBM forecast, beliefs, lasting effects)",
        f"against each baseline; 95% Wilson intervals; Python/NumPy seed {SEED}. Generated by",
        "`python scripts/run_headline.py --report`.",
        "",
        "| Strategy | Opponent | Games | Wins | Win rate | 95% interval |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['strategy']} | {r['opponent']} | {r['games']} | {r['wins']} |"
            f" {r['rate']:.1%} | {r['low']:.1%} to {r['high']:.1%} |"
        )
    beats = {(r["strategy"], r["opponent"]): r["low"] > 0.5 for r in rows}
    best = "best_response"
    lines += [
        "",
        "Success criteria (docs/09-evaluation-plan.md), best response:",
        f"- Minimum, beats random and max power: "
        f"{'yes' if beats.get((best, 'random')) and beats.get((best, 'max_power')) else 'no'}",
        f"- Target, beats SimpleHeuristicsPlayer: "
        f"{'yes' if beats.get((best, 'heuristics')) else 'no'}",
        "",
        f"Source commits: {', '.join(sorted({c for r in rows for c in r['commits']}))};"
        f" dates: {', '.join(sorted({d for r in rows for d in r['dates']}))}.",
    ]
    return "\n".join(lines) + "\n"
