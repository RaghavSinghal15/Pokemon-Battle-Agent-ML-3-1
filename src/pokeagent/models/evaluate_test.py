"""Final evaluation on the test split (E5, #38). Run once, after every model choice is made.

    python -m pokeagent.models.evaluate_test

Every model choice (features, hyperparameters, which model the agent uses) was made on the
validation split. This script loads the saved models from artifacts/ and scores them on the
test split, which nothing else reads. It refuses to run a second time unless given --again,
so the test numbers cannot quietly become a second validation set.

Writes reports/results/test_evaluation.json and test_evaluation.md (metrics only).

Uncertainty: rows from the same game are not independent, so the intervals come from a
paired bootstrap over games (resample whole games with replacement, recompute the
difference in mean log loss between two models on the same resampled games).
"""

import argparse
import json
import pickle

import numpy as np

from pokeagent.config import ARTIFACTS_DIR, REPORTS_DIR, SEED, VALUE_UTILITY_MODEL_PATH
from pokeagent.interfaces import ACTION_CLASSES
from pokeagent.models.calibration import expected_calibration_error, reliability_table
from pokeagent.models.opponent import (
    LABEL,
    all_turn_losses,
    evaluate,
    evaluate_all_turns,
    load_split,
)
from pokeagent.models.value import evaluate_value, load_value_split, mirror_gap

REPORT_JSON = REPORTS_DIR / "results" / "test_evaluation.json"
REPORT_MD = REPORTS_DIR / "results" / "test_evaluation.md"
OPPONENT_KEYS = ("naive", "naive_hidden", "logistic_regression", "lightgbm", "lightgbm_hidden")
CHOSEN_OPPONENT = "lightgbm_hidden"  # chosen on validation (opponent_model_val.json)
VALUE_KEYS = ("team_hp", "logistic_regression", "lightgbm")
BOOTSTRAP_ROUNDS = 1000


def load_model(name: str):
    with (ARTIFACTS_DIR / f"{name}.pkl").open("rb") as stream:
        return pickle.load(stream)


def paired_bootstrap(losses_a, losses_b, games, rounds=BOOTSTRAP_ROUNDS, seed=SEED) -> dict:
    """Mean of (loss A - loss B) per row, with a 95% interval from resampling whole games.

    Negative means model A is better. Each game's rows are summed first, so a resampled game
    counts with all of its rows, the way it was played.
    """
    games = np.asarray(games)
    ids, index = np.unique(games, return_inverse=True)
    diff_sum = np.bincount(index, weights=np.asarray(losses_a) - np.asarray(losses_b))
    rows = np.bincount(index).astype(float)
    rng = np.random.default_rng(seed)
    estimates = []
    for _ in range(rounds):
        pick = rng.integers(0, len(ids), len(ids))
        estimates.append(diff_sum[pick].sum() / rows[pick].sum())
    low, high = np.percentile(estimates, [2.5, 97.5])
    return {"difference": float(diff_sum.sum() / rows.sum()), "ci95": [float(low), float(high)]}


def opponent_section() -> dict:
    test = load_split("test", allow_test=True)
    test_all = load_split("test", allow_test=True, with_hidden=True)
    models = {key: load_model(f"opponent_model_{key}") for key in OPPONENT_KEYS}
    switched = (test_all[LABEL] == "switch").to_numpy()
    column = ACTION_CLASSES.index("switch")
    results, losses = {}, {}
    for key, model in models.items():
        results[key] = {
            **evaluate_all_turns(model, test_all),
            "visible_only": evaluate(model, test),
        }
        p_switch = model.predict_proba_table(test_all)[:, column]
        results[key]["switch_ece"] = expected_calibration_error(
            reliability_table(p_switch, switched)
        )
        losses[key] = all_turn_losses(model, test_all)
    games = test_all["battle_id"].to_numpy()
    comparisons = {
        f"{CHOSEN_OPPONENT} - {other}": paired_bootstrap(
            losses[CHOSEN_OPPONENT], losses[other], games
        )
        for other in ("naive_hidden", "logistic_regression", "lightgbm")
    }
    return {
        "rows": len(test_all),
        "hidden_rows": int((test_all[LABEL] == "hidden").sum()),
        "games": int(len(np.unique(games))),
        "chosen": CHOSEN_OPPONENT,
        "results": results,
        "paired_bootstrap_all_turns": comparisons,
    }


def value_section() -> dict:
    test = load_value_split("test", allow_test=True)
    results = {}
    for key in VALUE_KEYS:
        model = load_model(f"value_model_{key}")
        results[key] = {**evaluate_value(model, test), "mirror_gap": mirror_gap(model, test)}
    used = VALUE_UTILITY_MODEL_PATH.stem.removeprefix("value_model_")
    return {"rows": len(test), "used_by_agent": used, "results": results}


def markdown(report: dict) -> str:
    opp, val = report["opponent_model"], report["value_model"]
    lines = [
        "# Test-split evaluation (E5)",
        "",
        "Run once, after every model choice was made on validation. Generated by",
        "`python -m pokeagent.models.evaluate_test`.",
        "",
        f"## Opponent model: {opp['rows']:,} turns ({opp['hidden_rows']:,} hidden)"
        f" from {opp['games']:,} games",
        "",
        "Log loss on all turns is the headline metric (lower is better; a uniform guess is"
        f" {np.log(3):.4f}).",
        "",
        "| Model | All-turns log loss | Visible log loss | Accuracy | Macro F1 | Switch ECE |",
        "|---|---|---|---|---|---|",
    ]
    for key, r in opp["results"].items():
        v = r["visible_only"]
        mark = " (used)" if key == opp["chosen"] else ""
        lines.append(
            f"| {r['model']}{mark} | {r['all_turns_log_loss']:.4f} | {v['log_loss']:.4f} |"
            f" {v['accuracy']:.3f} | {v['macro_f1']:.3f} | {r['switch_ece']:.3f} |"
        )
    lines += [
        "",
        "Paired bootstrap over games (difference in all-turns log loss; negative = the used",
        "model is better):",
        "",
    ]
    for name, b in opp["paired_bootstrap_all_turns"].items():
        low, high = b["ci95"]
        lines.append(f"- {name}: {b['difference']:+.4f} (95% interval {low:+.4f} to {high:+.4f})")
    lines += [
        "",
        f"## Value model: {val['rows']:,} positions",
        "",
        "| Model | Log loss | Brier | Accuracy | AUC | ECE | Mirror gap |",
        "|---|---|---|---|---|---|---|",
    ]
    for key, r in val["results"].items():
        mark = " (used)" if key == val["used_by_agent"] else ""
        lines.append(
            f"| {key}{mark} | {r['log_loss']:.4f} | {r['brier']:.4f} | {r['accuracy']:.3f} |"
            f" {r['auc']:.3f} | {r['ece']:.3f} | {r['mirror_gap']:.3f} |"
        )
    return "\n".join(lines) + "\n"


def main(again: bool = False) -> None:
    if REPORT_JSON.exists() and not again:
        raise SystemExit(
            f"{REPORT_JSON} already exists: the test split has been used. Pass --again only"
            " to reproduce the same numbers, never to choose between models."
        )
    report = {"split": "test", "opponent_model": opponent_section(), "value_model": value_section()}
    REPORT_JSON.parent.mkdir(parents=True, exist_ok=True)
    REPORT_JSON.write_text(json.dumps(report, indent=2), encoding="utf-8")
    REPORT_MD.write_text(markdown(report), encoding="utf-8")
    print(markdown(report))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--again", action="store_true", help="reproduce an earlier run")
    main(parser.parse_args().again)
